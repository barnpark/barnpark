// ข้อความประกาศจากรายการที่เลือก (หัวข้อ ≤ 80 ตัว · รายละเอียด ≤ 1500 ตัว ตามข้อจำกัดของหน้าแอดมิน)
export function composeAnnouncement(ids) {
  const list = CHANGELOG.filter((c) => ids.includes(c.id));
  if (!list.length) return { title: "", message: "" };
  const title = list.length === 1 ? list[0].title : "อัปเดตใหม่: " + list.map((c) => c.title).join(" · ");
  const message = list.map((c) => `✨ ${c.title}\n${c.items.map((i) => "• " + i).join("\n")}`).join("\n\n");
  const cut = (s, n) => (Array.from(s).length > n ? Array.from(s).slice(0, n - 1).join("") + "…" : s);
  return { title: cut(title, 80), message: cut(message, 1500) };
}
